#!/usr/bin/env python3
"""
Builds a SHiVAi BIDS-format input folder using symlinks, by matching:
  - raw BIDS MRI data (T1w, FLAIR, SWI)      -> RAW_DIR
  - FreeSurfer aparc+aseg.mgz segmentations  -> SEG_DIR

Output layout (session level collapsed away, matching SHiVAi's BIDS
datagrabber template, confirmed empirically against real pipeline errors):
  shivai_symlinks/<PREDICTION>_<BRAIN_SEG>/batch_XXX/sub-XXXX/anat/sub-XXXX_T1w.nii.gz
  sub-XXXX/anat/sub-XXXX_FLAIR.nii.gz   (only if FLAIR is required - see below)
  sub-XXXX/anat/sub-XXXX_SWI.nii.gz     (only if SWI is required - see below)
  sub-XXXX/anat/aparc+aseg.mgz          (only if a FreeSurfer seg is required)

A subject is included in the output folder ONLY if every modality required by
your actual --prediction / --brain_seg settings is found. Partial subjects
(missing something required) are excluded entirely - no partial folders are
ever created. This matches how SHiVAi actually behaves: with
--brain_seg fs_precomp, a missing segmentation is NOT auto-generated by
SHiVAi - the run just fails for that subject. Same logic applies to
prediction-specific modalities (e.g. CMB needs SWI - if it's missing,
that subject cannot produce a CMB result).

REQUIRED_MODALITIES is derived automatically from PREDICTIONS and BRAIN_SEG
below - keep these in sync with your actual `shiva` command line.

Session selection: prefers ses-bl (baseline); falls back to ses-fu if ses-bl
is absent. If neither exists (even if other ses-* folders are present), the
subject is skipped and flagged - this check happens first, before any file
lookups, since without a session there's nothing to look inside.

Ambiguous matches (e.g. multiple T1w files in one session) are reported
immediately as they're found, in addition to being counted in the summary.

Every run (when not a dry run) fully rebuilds that prediction+brain_seg
OUT_DIR from scratch. Other combos (e.g. CMB_shiva vs CMB_fs_precomp) are
left untouched.

Two report outputs are written under OUT_DIR:
  - index.csv (included subjects: session, batch, source paths)
  - excluded_subjects.csv (ALL excluded subjects with reasons, for review)

Run a DRY RUN first (default) to review the report before creating symlinks.
"""

import csv
import os
import shutil
from pathlib import Path

# ---------------- CONFIG: edit these to match your actual `shiva` command ----------------
PROJECT_ROOT = Path("/data/pt_life/ResearchProjects/Sheker/SHiVAi_master")
RAW_DIR = Path("/data/pt_life/ResearchProjects/Sheker/SHiVAi_master/shivai_test")
SEG_DIR = Path("/data/pt_life_freesurfer/freesurfer_all")

DRY_RUN = True   # set to False once you've reviewed the report and are ready to create symlinks

# Match these EXACTLY to your `shiva --prediction ... --brain_seg ...` flags.
PREDICTIONS = ["PVS2", "WMH", "CMB"]          # e.g. ["PVS"], ["PVS2", "WMH"], ["CMB"], etc.
BRAIN_SEG = "shiva"       # e.g. "fs_precomp", "shiva", "synthseg", "premasked", "custom"
CHUNK_SIZE = 5   # e.g. 200 -> batch_001, batch_002, ... of 200 subjects each; None = no chunking
# -------------------------------------------------------------------------------------------


def input_folder_name(predictions, brain_seg):
    """Input tree name, e.g. CMB_shiva or CMB_fs_precomp."""
    return f"{'+'.join(predictions)}_{brain_seg}"


OUT_DIR = PROJECT_ROOT / "shivai_symlinks" / input_folder_name(PREDICTIONS, BRAIN_SEG)
EXCLUDED_REPORT_PATH = OUT_DIR / "excluded_subjects.csv"
INDEX_PATH = OUT_DIR / "index.csv"

# Explicit session priority order: try these in sequence.
# Anything not in this list is ignored entirely (not used as a silent fallback).
SESSION_PRIORITY = ["ses-bl", "ses-fu"]


def compute_required_modalities(predictions, brain_seg):
    """
    Derives which modalities are actually required, based on the real
    --prediction and --brain_seg values this symlink tree will be used with.
    T1w is always required. FLAIR is needed by PVS2/WMH/LAC. SWI is needed
    by CMB. A FreeSurfer segmentation is required only when brain_seg is
    fs_precomp (SHiVAi does not auto-generate one in that mode).
    """
    required = {"T1w"}
    if any(p in predictions for p in ("PVS2", "WMH", "LAC")):
        required.add("FLAIR")
    if "CMB" in predictions:
        required.add("SWI")
    if brain_seg == "fs_precomp":
        required.add("SEG")
    return required


REQUIRED_MODALITIES = compute_required_modalities(PREDICTIONS, BRAIN_SEG)


def find_sessions(subj_dir: Path):
    """Return sorted list of session dirs (ses-*) under a subject folder."""
    return sorted([d for d in subj_dir.iterdir() if d.is_dir() and d.name.startswith("ses-")])


def choose_session(sessions):
    """
    Picks a session according to SESSION_PRIORITY (ses-bl first, then ses-fu).
    Returns (session_dir, used_fallback). Returns (None, None) if neither
    preferred session exists, even if other ses-* folders are present
    (those are intentionally not used).
    """
    available = {s.name: s for s in sessions}
    for i, pref in enumerate(SESSION_PRIORITY):
        if pref in available:
            return available[pref], (i > 0)
    return None, None


def find_modality_file(session_dir: Path, modality: str, exclude_acq_tag: bool = False):
    """
    Searches session_dir/anat for files matching *<modality>.nii.gz
    modality: 'T1w', 'FLAIR', or 'swi'.
    If exclude_acq_tag=True, skips files containing 'acq-' - used for SWI,
    to exclude acq-mag/acq-ph (raw components) and acq-mip (a projection),
    keeping only the plain reconstructed/combined SWI volume.
    Returns (path, ambiguous_bool) or (None, False) if not found.
    """
    anat_dir = session_dir / "anat"
    if not anat_dir.is_dir():
        return None, False
    matches = sorted(anat_dir.glob(f"*{modality}.nii.gz"))
    if exclude_acq_tag:
        matches = [f for f in matches if "acq-" not in f.name]
    if not matches:
        return None, False
    return matches[0], len(matches) > 1


def find_freesurfer_seg(subject_id_no_prefix: str):
    """
    Looks for SEG_DIR/<id>/mri/aparc+aseg.mgz. Bare subject ID (no sub-
    prefix), which also implicitly excludes _temp / .long.* reprocessing
    variants since those have different folder names entirely.
    """
    candidate = SEG_DIR / subject_id_no_prefix / "mri" / "aparc+aseg.mgz"
    return candidate if candidate.is_file() else None


def make_symlink(src: Path, dst: Path, dry_run: bool):
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.exists() or dst.is_symlink():
        dst.unlink()
    if not dry_run:
        os.symlink(src, dst)


def gather_subject_files(subj_dir: Path):
    """
    Looks up every modality for one subject, WITHOUT creating any symlinks.
    Returns a dict describing what was found, what's missing (relative to
    REQUIRED_MODALITIES), and any ambiguous matches - so the caller can
    decide whether to include or exclude the subject before touching the
    filesystem.
    """
    subj_id = subj_dir.name
    bare_id = subj_id.replace("sub-", "", 1)

    result = {
        "subj_id": subj_id,
        "session": None,
        "session_fallback_used": False,
        "files": {},          # modality -> Path
        "ambiguous": [],      # list of modality names that had multiple matches
        "missing_required": [],
        "excluded": False,
        "exclusion_reason": None,
    }

    sessions = find_sessions(subj_dir)
    session, is_fallback = choose_session(sessions)
    if session is None:
        available_names = [s.name for s in sessions] if sessions else "none"
        result["excluded"] = True
        result["exclusion_reason"] = f"no ses-bl or ses-fu found (available sessions: {available_names})"
        return result

    result["session"] = session.name
    result["session_fallback_used"] = is_fallback

    t1_file, t1_amb = find_modality_file(session, "T1w")
    flair_file, flair_amb = find_modality_file(session, "FLAIR")
    swi_file, swi_amb = find_modality_file(session, "swi", exclude_acq_tag=True)
    seg_file = find_freesurfer_seg(bare_id)

    candidates = {"T1w": t1_file, "FLAIR": flair_file, "SWI": swi_file, "SEG": seg_file}
    ambiguity = {"T1w": t1_amb, "FLAIR": flair_amb, "SWI": swi_amb, "SEG": False}

    for modality, path in candidates.items():
        if path is not None:
            result["files"][modality] = path
        if ambiguity[modality]:
            result["ambiguous"].append(modality)
            # Reported immediately, at the point of discovery, not just batched later.
            print(f"  [ambiguous] {subj_id}: multiple {modality} matches found, "
                  f"using first (sorted): {path.name}")

    for modality in REQUIRED_MODALITIES:
        if modality not in result["files"]:
            result["missing_required"].append(modality)

    if result["missing_required"]:
        result["excluded"] = True
        result["exclusion_reason"] = f"missing required: {', '.join(result['missing_required'])}"

    return result


def write_subject_symlinks(info: dict, base_dir: Path, dry_run: bool):
    """
    Creates symlinks for a subject that has already been confirmed complete.
    base_dir is either OUT_DIR (no chunking) or a specific batch subfolder
    (e.g. OUT_DIR/batch_003), depending on CHUNK_SIZE.
    Only writes files that are actually present in info['files'] - i.e. only
    modalities that are both required AND found, keeping the output tree
    free of anything not needed for the configured --prediction/--brain_seg.
    """
    subj_id = info["subj_id"]
    files = info["files"]
 
    if "T1w" in files:
        dst = base_dir / subj_id / "anat" / f"{subj_id}_T1w.nii.gz"
        make_symlink(files["T1w"], dst, dry_run)
    if "FLAIR" in files:
        dst = base_dir / subj_id / "anat" / f"{subj_id}_FLAIR.nii.gz"
        make_symlink(files["FLAIR"], dst, dry_run)
    if "SWI" in files:
        dst = base_dir / subj_id / "anat" / f"{subj_id}_SWI.nii.gz"
        make_symlink(files["SWI"], dst, dry_run)
    if "SEG" in files:
        # Confirmed via actual pipeline error: template is sub-XXXX/anat/*aparc+aseg.*
        dst = base_dir / subj_id / "anat" / "aparc+aseg.mgz"
        make_symlink(files["SEG"], dst, dry_run)


def chunked(items, size):
    """Splits a list into consecutive sublists of at most `size` items each."""
    if not size:
        return [items]
    return [items[i:i + size] for i in range(0, len(items), size)]



def _source_path(info, modality):
    path = info["files"].get(modality)
    return str(path) if path else ""


def write_included_index(rows, path: Path):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow([
            "subject_id", "session", "session_fallback_used", "batch",
            "t1", "flair", "swi", "seg",
        ])
        for info in rows:
            writer.writerow([
                info["subj_id"],
                info["session"] or "",
                info["session_fallback_used"],
                info.get("batch", ""),
                _source_path(info, "T1w"),
                _source_path(info, "FLAIR"),
                _source_path(info, "SWI"),
                _source_path(info, "SEG"),
            ])


def main():
    print(f"Required modalities for PREDICTIONS={PREDICTIONS}, BRAIN_SEG={BRAIN_SEG!r}: "
          f"{sorted(REQUIRED_MODALITIES)}")
    print(f"Input tree: {OUT_DIR}\n")
    
    subjects = sorted([d for d in RAW_DIR.iterdir() if d.is_dir() and d.name.startswith("sub-")])
    print(f"Found {len(subjects)} subjects in raw data folder.\n")
 
    # Rebuild only this prediction's OUT_DIR from scratch on real runs, so
    # re-running never accumulates stale symlinks. Other prediction folders
    # (e.g. shivai_symlinks/CMB_fs_precomp) are left untouched.
    if not DRY_RUN and OUT_DIR.exists():
        print(f"Removing existing {OUT_DIR} to rebuild cleanly...")
        shutil.rmtree(OUT_DIR)
 
    ready_subjects = []
    excluded_subjects = []
    fallback_session_count = 0
    ambiguous_count = 0
 
    for subj_dir in subjects:
        info = gather_subject_files(subj_dir)
 
        if info["session_fallback_used"]:
            fallback_session_count += 1
        if info["ambiguous"]:
            ambiguous_count += 1
 
        if info["excluded"]:
            excluded_subjects.append(info)
            continue
 
        ready_subjects.append(info)
 
    # Write symlinks after all subjects are evaluated, so ready_subjects can
    # be split into chunks first. chunked() returns [ready_subjects] as one
    # batch when CHUNK_SIZE is None, so this loop works either way.
    for batch_idx, batch in enumerate(chunked(ready_subjects, CHUNK_SIZE), start=1):
        batch_name = f"batch_{batch_idx:03d}" if CHUNK_SIZE else ""
        base_dir = OUT_DIR / batch_name if batch_name else OUT_DIR
        for info in batch:
            info["batch"] = batch_name
            write_subject_symlinks(info, base_dir, DRY_RUN)
 
    # ---------------- Report ----------------
    print("\n===== SUMMARY =====")
    print(f"Total subjects checked: {len(subjects)}")
    print(f"Ready (all required modalities found, symlinks {'would be' if DRY_RUN else ''} created): {len(ready_subjects)}")
    print(f"Excluded (missing something required, or no usable session): {len(excluded_subjects)}")
    print(f"Used ses-fu fallback (ses-bl not available): {fallback_session_count}")
    print(f"Subjects with at least one ambiguous match: {ambiguous_count}")
 
    if excluded_subjects:
        print(f"\n===== First 20 excluded subjects (of {len(excluded_subjects)} total, see CSV for full list) =====")
        for info in excluded_subjects[:20]:
            print(f"  {info['subj_id']}: {info['exclusion_reason']}")
        if len(excluded_subjects) > 20:
            print(f"  ... and {len(excluded_subjects) - 20} more — see {EXCLUDED_REPORT_PATH}")
 
    # Full excluded-subjects report, always written (even on dry runs) so it
    # can be reviewed/shared without scrolling terminal output.
    # Uses one explicit column per modality (missing_T1w, missing_FLAIR, etc.)
    # rather than a single free-text reason string, so the CSV can be
    # directly filtered/sorted in Excel/Sheets/pandas (e.g. "show me only
    # subjects missing SEG") without parsing text.
    EXCLUDED_REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(EXCLUDED_REPORT_PATH, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow([
            "subject_id", "no_session_found",
            "missing_T1w", "missing_FLAIR", "missing_SWI", "missing_SEG",
            "reason",
        ])
        for info in excluded_subjects:
            missing = set(info["missing_required"])
            no_session = info["exclusion_reason"] is not None and "no ses-bl or ses-fu" in info["exclusion_reason"]
            writer.writerow([
                info["subj_id"],
                no_session,
                "T1w" in missing,
                "FLAIR" in missing,
                "SWI" in missing,
                "SEG" in missing,
                info["exclusion_reason"],
            ])
    print(f"\nFull excluded-subjects list written to: {EXCLUDED_REPORT_PATH}")
    write_included_index(ready_subjects, INDEX_PATH)
    print(f"Included-subjects index written to: {INDEX_PATH}")
 
    print()
    if DRY_RUN:
        print(">>> DRY RUN — no symlinks were created. Review the report above, "
              "then set DRY_RUN = False to actually build the folder.")
    else:
        if CHUNK_SIZE:
            n_chunks = len(chunked(ready_subjects, CHUNK_SIZE))
            print(f">>> Symlinks created in: {OUT_DIR}/batch_001 .. batch_{n_chunks:03d}")
        else:
            print(f">>> Symlinks created in: {OUT_DIR}")
        print(f">>> {len(ready_subjects)} subjects included, {len(excluded_subjects)} excluded.")
 
 


if __name__ == "__main__":
    main()



